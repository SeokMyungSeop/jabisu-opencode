// Writes src/plugin/jabisu/bundle.ts, which imports every file under src/plugin/jabisu/skills so the compiled CLI
// embeds them. Run it after adding, removing or renaming a bundled skill file: `bun run script/jabisu-bundle.ts`.
import path from "path"
import { Glob } from "bun"

const root = path.join(import.meta.dirname, "../src/plugin/jabisu")
// Binary files embed as files the plugin copies; everything else embeds as text.
const BINARY = new Set([".hwpx", ".png"])

const files = (await Array.fromAsync(new Glob("skills/**/*").scan({ cwd: root, dot: true })))
  .map((file) => file.split(path.sep).join("/"))
  .toSorted()
const imports = files.map((file, index) => {
  const type = BINARY.has(path.extname(file)) ? "file" : "text"
  return `import file${index} from "./${file}" with { type: "${type}" }`
})
const entries = files.map((file, index) => {
  const name = file.slice("skills/".length)
  // Bun's types describe some extensions, such as .xml, as parsed values; the text attribute makes them strings.
  return BINARY.has(path.extname(file))
    ? `  { path: "${name}", file: file${index} },`
    : `  { path: "${name}", text: String(file${index}) },`
})

await Bun.write(
  path.join(root, "bundle.ts"),
  [
    "// Generated by script/jabisu-bundle.ts from the files under ./skills; do not edit.",
    '/// <reference path="../../markdown.d.ts" />',
    '/// <reference path="./assets.d.ts" />',
    "",
    'export * as JabisuBundle from "./bundle.js"',
    "",
    ...imports,
    "",
    "/** Each bundled skill file by its path under the skills folder, as text or as the path of an embedded file. */",
    "export const files: ReadonlyArray<{ readonly path: string; readonly text: string } | { readonly path: string; readonly file: string }> = [",
    ...entries,
    "]",
    "",
  ].join("\n"),
)
console.log(`bundle.ts lists ${files.length} files`)
